def cal_marks(ser, mm, year, nxt=None, dates=None):
    out = []
    for m in mm:
        k = f"{year}.{m + 1:02d}"
        pk = f"{year - 1}.12" if m == 0 else f"{year}.{m:02d}"
        d = round(ser[k] - ser[pk], 2)
        q = {"m": m, "kind": "up" if d > 0 else "down" if d < 0 else "hold", "res": "인상" if d > 0 else "인하" if d < 0 else "동결", "rate": f"{ser[k]:.2f}%"}
        if d:
            q["size"] = f"{abs(d):.2f}%p"
        if dates and m in dates:
            q["date"] = dates[m]
        out.append(q)
    if nxt:
        out.append({"m": nxt[0], "kind": "next", "res": "예정", "date": nxt[1]})
    return out



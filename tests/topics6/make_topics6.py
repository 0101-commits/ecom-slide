from pathlib import Path

HERE = Path(__file__).resolve().parent


def deck(code, title, meta, slides):
    m = {"session": code, "title": title, "date": "2026.11.26", "cover": "E", "combo": "A"}
    m.update(meta)
    (HERE / f"{code}.json").write_text(json.dumps({"schema": 3, "meta": m, "facts": {}, "slides": slides}, ensure_ascii=False, indent=1), encoding="utf-8", newline="\n")


def ecom(group, topic, basis, head, blocks, layout="full", source="", notes=None, **kw):
    s = {"kind": "blocks", "eyebrow": {"group": group, "topic": topic, "basis": basis}, "head": head, "layout": layout, "blocks": blocks, "foot": {"source": source, "notes": notes or []}}
    s.update(kw)
    return s


def bento(title, sub, blocks, layout="full", source="", **kw):
    s = {"kind": "blocks", "frame": "bento", "title": title, "sub": sub, "layout": layout, "blocks": blocks, "foot": {"source": source, "notes": []}}
    s.update(kw)
    return s


